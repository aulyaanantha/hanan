-- Celebration data is accessed only by the server's service role.
create table if not exists public.special_days (
  id bigint generated by default as identity primary key,
  name text not null,
  date date not null,
  year integer not null check (year = extract(year from date)),
  category text not null check (category in ('national', 'religious', 'international')),
  description text not null,
  image_url text,
  source text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (name, year)
);
create index if not exists special_days_date_idx on public.special_days (date);
alter table public.special_days enable row level security;
revoke all on public.special_days from anon, authenticated;

-- One atomic claim per celebration and recipient. A claim is made before sending:
-- this favours avoiding duplicates over retrying an ambiguous delivery.
create table if not exists public.celebration_notification_log (
  special_day_id bigint not null references public.special_days(id),
  occurrence_date date not null,
  person text not null check (person in ('Farhan', 'Anantha')),
  created_at timestamptz not null default now(),
  primary key (special_day_id, occurrence_date, person)
);
alter table public.celebration_notification_log enable row level security;
revoke all on public.celebration_notification_log from anon, authenticated;
